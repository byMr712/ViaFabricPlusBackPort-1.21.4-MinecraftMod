package com.viaversion.viafabricplus.injection.mixin.base.ui;

import com.viaversion.viafabricplus.util.TextSanitizer;
import net.minecraft.client.gui.screen.DisconnectedScreen;
import net.minecraft.network.DisconnectionInfo;
import net.minecraft.text.Text;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Redirect;

@Mixin(DisconnectedScreen.class)
public abstract class MixinDisconnectedScreen {

    @Redirect(method = "init", at = @At(value = "INVOKE", target = "Lnet/minecraft/network/DisconnectionInfo;reason()Lnet/minecraft/text/Text;"))
    private Text makeReadableReason(DisconnectionInfo instance) {
        return TextSanitizer.makeHighContrast(instance.reason());
    }

}
